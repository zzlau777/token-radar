// The token radar's model, radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol the snapshot's own rule calls pre-token and launchable: the 40 on
// the watchlist plus every pre-token protocol below the floor that is not a wrapped, staked or
// bridged product, not an exchange and not a versioned pool. Protocols whose token already trades
// are kept apart in the Live view and shown at the market's own value, never mixed into the board.
//
// Implied value is a comparables model, built only from the snapshot's own figures:
//
//   multiple   = the category's median market-cap-per-TVL among live-token protocols, shrunk
//                toward the global median when the category has few live names, clamped to
//                [0.05, 2.00]; a protocol with no category takes the global median.
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x 0.6
//   maturity   = 0.7 + min(age_days, 1460) / 1460 x 0.3   (age_days unknown: 365)
//   breadth    = 1 + 0.02 x min(chains - 1, 5)
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row, and the dashboard
// states the multiple each category got so a reader can check the arithmetic.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

